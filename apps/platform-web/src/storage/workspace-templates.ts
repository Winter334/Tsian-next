  "const MAX_WRITES = 12;",
  "const MAX_CONTENT_LENGTH = 200000;",
  "",
  "function isAllowedTarget(path) {",
  "  return /^save\\/agents\\/[^/]+\\/notes\\.md$/.test(path)",
