function text(lines: string[]): string {
  return `${lines.join("\n")}\n`
}

function json(value: unknown): string {
  return `${JSON.stringify(value, null, 2)}\n`
}

function agentConfigContent(config: AgentConfig): string {
  return json(config)
}

