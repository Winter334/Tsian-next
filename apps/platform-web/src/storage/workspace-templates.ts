  "    || path === 'save/memory/summaries/current.md'",
  "    || path === 'save/memory/summaries/long-term.md';",
  "}",
  "",
  "function requireReason(rawWrite, path, index) {",
  "  if (typeof rawWrite.reason !== 'string' || !rawWrite.reason.trim()) fail('MAINTENANCE_REASON_REQUIRED', 'Maintenance write reason must be a non-empty string.', { index, path });",
  "  return rawWrite.reason.trim();",
  "}",
  "async function resolveModeAndFields(rawWrite, path, index, tsian) {",
  "  const hasEditInput = typeof rawWrite.oldString === 'string' && rawWrite.oldString.length > 0 && typeof rawWrite.newString === 'string';",
  "  const hasReplaceInput = typeof rawWrite.content === 'string';",
  "  let mode = typeof rawWrite.mode === 'string' ? rawWrite.mode : null;",
  "  if (!mode) {",
  "    if (hasEditInput) mode = 'edit';",
  "    else if (hasReplaceInput) mode = 'replace';",
  "    else fail('MAINTENANCE_WRITE_FIELDS_REQUIRED', 'Maintenance write must provide content (replace) or oldString+newString (edit).', { index, path });",
  "  }",
  "  if (mode !== 'replace' && mode !== 'edit') fail('MAINTENANCE_MODE_UNSUPPORTED', 'Maintenance write mode must be replace or edit.', { index, path, mode });",
  "  if (mode === 'replace') {",
  "    if (!hasReplaceInput) fail('MAINTENANCE_CONTENT_REQUIRED', 'Maintenance write content must be a string.', { index, path });",
  "    if (rawWrite.content.length > MAX_CONTENT_LENGTH) fail('MAINTENANCE_CONTENT_TOO_LARGE', 'Maintenance write content exceeds the allowed size.', { index, path, size: rawWrite.content.length, maxSize: MAX_CONTENT_LENGTH });",
  "    return { mode, content: rawWrite.content };",
  "  }",
  "  if (!hasEditInput) fail('MAINTENANCE_EDIT_FIELDS_REQUIRED', 'Maintenance write edit requires non-empty oldString and newString.', { index, path });",
  "  if (rawWrite.oldString.length > MAX_CONTENT_LENGTH || rawWrite.newString.length > MAX_CONTENT_LENGTH) fail('MAINTENANCE_EDIT_TOO_LARGE', 'Maintenance write edit strings exceed the allowed size.', { index, path });",
  "  return { mode, oldString: rawWrite.oldString, newString: rawWrite.newString, replaceAll: rawWrite.replaceAll === true };",
  "}",
  "function validateWrite(rawWrite, index) {",
  "  if (!isRecord(rawWrite)) fail('MAINTENANCE_WRITE_INVALID', 'Each maintenance write must be an object.', { index });",
  "  const path = normalizePath(rawWrite.path, 'MAINTENANCE');",
  "  if (!isAllowedTarget(path)) fail('MAINTENANCE_TARGET_NOT_ALLOWED', 'Maintenance write target is not allowed in this Skill.', { index, path });",
  "  const reason = requireReason(rawWrite, path, index);",
  "  return { path, reason, rawWrite };",
  "}",
  "",
  "function validatePlan(plan) {",
  "  if (!isRecord(plan)) fail('MAINTENANCE_PLAN_INVALID', 'Maintenance plan must be an object.');",
  "  if (plan.schema !== PLAN_SCHEMA) fail('MAINTENANCE_SCHEMA_INVALID', 'Maintenance plan schema is invalid.', { expected: PLAN_SCHEMA, actual: plan.schema });",
  "  if (!Array.isArray(plan.writes)) fail('MAINTENANCE_WRITES_INVALID', 'Maintenance plan writes must be an array.');",
  "  if (plan.writes.length > MAX_WRITES) fail('MAINTENANCE_TOO_MANY_WRITES', 'Maintenance plan contains too many writes.', { count: plan.writes.length, maxWrites: MAX_WRITES });",
  "  return plan.writes.map(validateWrite);",
  "}",
  "",
  "async function applyMaintenancePlan(input, tsian, signal) {",
  "  try {",
  "    signal.throwIfAborted();",
