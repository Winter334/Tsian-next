  "- 单向关系（如隶属）只写从属方。",
  "",
  "## frontier.notes 写法",
  "",
  "写为什么这个窗口足够开局: 哪些 inciting situation / protagonist context / conflict / setting cues 让你判断读够了。这也是 commit `window.reason` 的内容。",
  "",
  "## window.chapters 组装",
  "",
