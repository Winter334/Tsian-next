  "    var path, hadError = false;",
  "    try { path = normalizeString(chapter.path, 'OPENING_WINDOW_CHAPTER_PATH_REQUIRED', 'Window chapter path', 240); } catch (e) { errors.push({ field: 'chapters[' + index + '].path', code: e.code, message: e.message, details: e.details }); hadError = true; }",
