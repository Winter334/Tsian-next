  "    if (hadError) return null;",
  "    return { index: normalizePositiveInt(chapter.index, index + 1, 1, 999999), title: typeof chapter.title === 'string' ? chapter.title.trim() : '', path: path };",
  "  }).filter(function (c) { return c !== null; });",
  "  if (errors.length > 0) fail(errors[0].code, errors.length + ' field(s) failed; fix all and retry.', { fieldErrors: errors });",
